static u_short MarkTex[] = {
    PCX_B_MARK,         // "!" Bikkuri mark
    PCX_Q_MARK,         // "?" Question mark
    PCX_HEART           // heart
};
#define TEX_B_MARK      0
#define TEX_Q_MARK      1
#define TEX_HEART       2

void *AN_HeadMark( MATRIX *world, int mark )
{
    SVECTOR  *pos;
    PRESCRIPT pre;
    ANIMATION *anim;

    anim = 0;
    pos = &pre.pos;
    pos->vx = 0;
    pos->vy = 800;
    pos->vz = 0;

    pre.speed   = DG_ZeroVector;
    pre.scr_num = 0;
    pre.s_anim  = 0;

    switch ( mark )
    {
    case 0:
        anm_mark_form_800C13C8.tex = MarkTex[TEX_B_MARK];
        anim = &anm_mark_form_800C13C8;
        break;
    case 1:
        anm_mark_form_800C13C8.tex = MarkTex[TEX_Q_MARK];
        anim = &anm_mark_form_800C13C8;
        break;
    case 2:
        anm_mark_form_800C13E4.tex = MarkTex[TEX_B_MARK];
        anim = &anm_mark_form_800C13E4;
        break;
    case 3:
        anm_mark_form_800C13E4.tex = MarkTex[TEX_Q_MARK];
        anim = &anm_mark_form_800C13E4;
        break;
    case 4:
        anm_mark_form_800C1400.tex = MarkTex[TEX_B_MARK];
        anim = &anm_mark_form_800C1400;
        break;
    case 5:
        anm_mark_form_800C1400.tex = MarkTex[TEX_Q_MARK];
        anim = &anm_mark_form_800C1400;
        break;
    case 6:
        anm_mark_form_800C13C8.tex = MarkTex[TEX_HEART];
        anim = &anm_mark_form_800C13C8;
        break;
    }

    anim->pre_script = &pre;
    return NewAnime( world, 0, anim );
}
